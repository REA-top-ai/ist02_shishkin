s = "DeadlyParkourKillerDarkBrawlStarsAssassinSniper1999"

# 1. Третий символ строки (индекс 2)
print(f"1. Третий символ: {s[2]}")

# 2. Предпоследний символ
print(f"2. Предпоследний символ: {s[-2]}")

# 3. Первые пять символов
print(f"3. Первые пять символов: {s[:5]}")

# 4. Вся строка кроме последних двух символов
print(f"4. Без последних двух символов: {s[:-2]}")

# 5. Все символы с четными индексами
print(f"5. Символы с четными индексами: {s[::2]}")

# 6. Все символы с нечетными индексами
print(f"6. Символы с нечетными индексами: {s[1::2]}")

# 7. Все символы в обратном порядке
print(f"7. В обратном порядке: {s[::-1]}")

# 8. Все символы через один в обратном порядке
print(f"8. Через один в обратном порядке: {s[::-2]}")

# 9. Длина строки
print(f"9. Длина строки: {len(s)}")